import pandas as pd
import numpy as np

def bin_continuous_feature(data, num_bins=4, bin_type='width'):
    """
    Bins continuous data into categorical values.
    Supports function overloading via default parameters.

    Parameters:
    - data: The continuous feature column (pandas Series)
    - num_bins: Number of bins to create (default = 4)
    - bin_type: 'width' for Equal Width, 'frequency' for Equal Frequency (default = 'width')
    """
    if bin_type == 'width':
        # Equal width binning
        return pd.cut(data, bins=num_bins, labels=False, include_lowest=True)
    elif bin_type == 'frequency':
        # Equal frequency binning (quantiles)
        return pd.qcut(data, q=num_bins, labels=False, duplicates='drop')
    else:
        raise ValueError("Invalid bin_type. Choose 'width' or 'frequency'.")

