def equal_width_binning(data, num_bins=4):
    """Bins continuous data into equal width categorical bins (A1)."""
    min_val = np.min(data)
    max_val = np.max(data)
    bins = np.linspace(min_val, max_val, num_bins + 1)
    # pd.cut handles the assignment of values to bins automatically
    binned_data = pd.cut(data, bins=bins, labels=False, include_lowest=True)
    return binned_data

def calculate_entropy(target_col):
    """Calculates the entropy of a dataset using the formula H = -sum(p * log2(p))."""
    elements, counts = np.unique(target_col, return_counts=True)
    probabilities = counts / np.sum(counts)
    entropy = -np.sum(probabilities * np.log2(probabilities))
    return entropy

