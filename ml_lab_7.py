def build_custom_tree(data, features, target, depth=0, max_depth=3):
    """Recursively builds a custom Decision Tree using Information Gain."""
    # Base Case 1: If all target values are the same, return that value (Leaf Node)
    unique_targets = np.unique(data[target])
    if len(unique_targets) <= 1:
        return unique_targets[0]

    # Base Case 2: If no features left or max depth reached, return majority class
    if len(features) == 0 or depth == max_depth:
        return data[target].mode()[0]

    # Find the best feature to split on (Reusing the find_root_node logic from A3)
    best_feature, _ = find_root_node(data, features, target)

    # Initialize the tree structure
    tree = {best_feature: {}}
    remaining_features = [f for f in features if f != best_feature]

    # Grow branches for each unique value of the best feature
    for value in np.unique(data[best_feature]):
        subset = data[data[best_feature] == value]
        if subset.empty:
            tree[best_feature][value] = data[target].mode()[0]
        else:
            subtree = build_custom_tree(subset, remaining_features, target, depth + 1, max_depth)
            tree[best_feature][value] = subtree

    return tree

