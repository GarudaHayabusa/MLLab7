def information_gain(data, split_attribute_name, target_name):
    """Calculates the Information Gain of splitting a dataset on a given attribute."""

    # Calculate original entropy of the dataset
    total_entropy = calculate_entropy(data[target_name])

    # Calculate the unique values and counts for the proposed splitting attribute
    vals, counts = np.unique(data[split_attribute_name], return_counts=True)

    # Calculate the weighted entropy of the split
    weighted_entropy = 0
    for i in range(len(vals)):
        subset = data.where(data[split_attribute_name] == vals[i]).dropna()
        subset_prob = counts[i] / np.sum(counts)
        weighted_entropy += subset_prob * calculate_entropy(subset[target_name])

    # Information Gain is the drop in entropy
    info_gain = total_entropy - weighted_entropy
    return info_gain

def find_root_node(data, feature_columns, target_name):
    """Evaluates Information Gain for all features to find the best root node."""
    best_info_gain = -1
    best_feature = None

    for feature in feature_columns:
        # If the predictive feature is continuous numeric data, bin it first
        if pd.api.types.is_numeric_dtype(data[feature]):
             eval_feature = f'{feature}_binned'
             data[eval_feature] = equal_width_binning(data[feature], num_bins=4)
        else:
             eval_feature = feature

        ig = information_gain(data, eval_feature, target_name)
        print(f"Evaluated '{feature}' -> Information Gain: {ig:.4f}")

        if ig > best_info_gain:
            best_info_gain = ig
            best_feature = feature

    return best_feature, best_info_gain

